// Where published clips live and how the landing page learns about them.
// MEDIA_BASE must equal MEDIA_BASE in platform/portal/src/app/pages/landing/landing-clips.ts (tested).

export const MEDIA_BASE = 'https://media.cairnpaas.dev/v1';
export const PREFIX = 'v1';
export const SITE_ORIGIN = 'https://cairnpaas.dev';

export const FILES = [
  { suffix: '.mp4', type: 'video/mp4' },
  { suffix: '.webm', type: 'video/webm' },
  { suffix: '-poster.jpg', type: 'image/jpeg' },
  { suffix: '.en.vtt', type: 'text/vtt; charset=utf-8' },
];

/** The versions file the landing page imports. */
export function versionsModule(manifest) {
  const versions = Object.fromEntries(Object.entries(manifest.clips).map(([clip, info]) => [clip, info.version]).sort());
  return `// Generated by videos/recordings/publish.mjs from the uploaded clips' manifest.
// A clip appears on the landing page once it has a version here; until then the
// page shows "Recording coming soon". Versions follow file contents.
export const CLIP_VERSIONS: Readonly<Record<string, string>> = ${JSON.stringify(versions, null, 2)};
`;
}

