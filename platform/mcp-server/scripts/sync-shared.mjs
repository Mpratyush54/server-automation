#!/usr/bin/env node
/**
 * Copy the shared MCP tool registry from the API into src/shared/ before compiling.
 *
 * The remote /mcp endpoint (platform/api) and this stdio server expose the same tools. The single
 * source is platform/api/src/mcp/registry.ts; src/shared/ is generated and ignored by git.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '..', '..', 'api', 'src', 'mcp', 'registry.ts');
const targetDir = path.resolve(here, '..', 'src', 'shared');
const target = path.join(targetDir, 'registry.ts');

let text;
try {
  text = readFileSync(source, 'utf8');
} catch (err) {
  console.error(`[sync-shared] Cannot read ${source}. Build this package from a full checkout of the repository.`);
  process.exit(1);
}

mkdirSync(targetDir, { recursive: true });
const banner = '// GENERATED by scripts/sync-shared.mjs from platform/api/src/mcp/registry.ts. Do not edit.\n';
writeFileSync(target, banner + text);
console.log('[sync-shared] src/shared/registry.ts updated');
