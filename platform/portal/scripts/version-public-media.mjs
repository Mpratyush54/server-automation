import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const portal = fileURLToPath(new URL("../", import.meta.url));
const files = {
  overview: "platform-overview.mp4",
  portrait: "platform-short.mp4",
  overviewPoster: "platform-overview-poster.jpg",
  portraitPoster: "platform-short-poster.jpg",
  overviewCaptions: "platform-overview.en.vtt",
  portraitCaptions: "platform-short.en.vtt",
};
const media = {};
for (const [key, file] of Object.entries(files)) {
  const bytes = await readFile(join(portal, "public/media", file));
  const version = createHash("sha256").update(bytes).digest("hex").slice(0, 12);
  media[key] = `/media/${file}?v=${version}`;
}
await writeFile(
  join(portal, "src/app/pages/landing/landing-media.ts"),
  `// Generated by scripts/version-public-media.mjs. Versions follow file contents.\nexport const landingMedia = ${JSON.stringify(media, null, 2)} as const;\n`,
);
console.log("Versioned public media URLs for browser and CDN caches.");
