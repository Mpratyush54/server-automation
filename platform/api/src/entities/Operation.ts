import {
  Entity, PrimaryColumn, Column, CreateDateColumn, UpdateDateColumn, Index, OneToMany,
} from 'typeorm';
import { OperationStep } from './OperationStep';

export type OperationStatus =
  | 'pending'
  | 'running'
  | 'succeeded'
  | 'failed'
  | 'compensating'
  | 'compensated';

export const TERMINAL_OPERATION_STATUSES: OperationStatus[] = ['succeeded', 'failed', 'compensated'];

/**
 * A multi-step mutating operation (deploy, secret rotation, DB provisioning) with a
 * persisted step log, so a crashed or restarted API can resume or compensate it.
 */
@Entity('operations')
@Index(['status', 'updatedAt'])
export class Operation {
  /** Generated by the caller (before the resource lock is taken) so the lock can name its holder. */
  @PrimaryColumn('uuid')
  id: string;

  @Index()
  @Column({ type: 'varchar', length: 64 })
  type: string;

  @Index()
  @Column({ type: 'uuid', nullable: true, name: 'project_id' })
  projectId: string | null;

  /** Resource lock this operation runs under (e.g. lock:project:<id>:deploy:<env>). */
  @Index()
  @Column({ type: 'varchar', length: 255, nullable: true, name: 'lock_key' })
  lockKey: string | null;

  /** Fencing token of the runner that currently owns this operation; writes from stale runners are rejected. */
  @Column({ type: 'varchar', length: 64, nullable: true, name: 'lock_fence' })
  lockFence: string | null;

  @Column({ type: 'varchar', length: 32, default: 'pending' })
  status: OperationStatus;

  @Column({ type: 'int', default: 0, name: 'current_step' })
  currentStep: number;

  /** sha256 of the canonical input; lets callers detect "same request" vs "different request". */
  @Column({ type: 'varchar', length: 64, name: 'input_hash' })
  inputHash: string;

  /** Non-secret input needed to resume. */
  @Column({ type: 'jsonb', nullable: true })
  input: Record<string, unknown> | null;

  /** Non-secret working state shared between steps. */
  @Column({ type: 'jsonb', nullable: true })
  state: Record<string, unknown> | null;

  /**
   * Working state that contains credentials, AES-256-GCM encrypted with
   * SECRETS_ENCRYPTION_KEY (or JWT_SECRET). Wiped once the operation is terminal.
   */
  @Column({ type: 'text', nullable: true, name: 'state_encrypted' })
  stateEncrypted: string | null;

  @Column({ type: 'jsonb', nullable: true })
  result: Record<string, unknown> | null;

  @Column({ type: 'text', nullable: true })
  error: string | null;

  /** Number of times a runner picked the operation up (1 = original run, >1 = resumed). */
  @Column({ type: 'int', default: 0 })
  attempts: number;

  @Column({ type: 'uuid', nullable: true, name: 'created_by_id' })
  createdById: string | null;

  @OneToMany(() => OperationStep, (s) => s.operation)
  steps: OperationStep[];

  @CreateDateColumn({ name: 'created_at' })
  createdAt: Date;

  @UpdateDateColumn({ name: 'updated_at' })
  updatedAt: Date;

  @Column({ type: 'timestamp', nullable: true, name: 'finished_at' })
  finishedAt: Date | null;
}
