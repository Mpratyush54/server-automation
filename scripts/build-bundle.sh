#!/usr/bin/env bash
# Build the platformctl offline bundle: platform-bundle-<version>-<arch>.tar.zst
#
# Usage: scripts/build-bundle.sh <version> <arch>
#   version  release tag, e.g. v1.0.0
#   arch     amd64 | arm64
#
# Contents (installed by platformctl/internal/bundle):
#   SHA256SUMS                               checksums of every file below
#   manifest.json                            versions + file list
#   k3s/k3s-airgap-images-<arch>.tar.zst     k3s airgap images for versions.K3sVersion
#   images/platform-images-<arch>.tar.zst    docker save | zstd of internal/images/images.txt
#   charts/<name>-<version>.tgz              helm pull of every chart in `platformctl charts --json`
#
# Output: $OUT_DIR (default ./dist) gets the bundle and <bundle>.sha256.
#
# Requires: go (or $PLATFORMCTL / $CHARTS_JSON), curl, jq, helm (v3), docker, zstd, tar, sha256sum.
# Environment overrides:
#   OUT_DIR       output directory (default <repo>/dist)
#   IMAGES_TXT    image list (default platformctl/internal/images/images.txt)
#   PLATFORMCTL   prebuilt platformctl binary used for `charts --json`
#   CHARTS_JSON   path to a pre-generated `charts --json` file
#   ZSTD_LEVEL    compression level for the image tarball (default 10)
set -euo pipefail

die() { echo "build-bundle: error: $*" >&2; exit 1; }
log() { echo "build-bundle: $*" >&2; }

[[ $# -eq 2 ]] || die "usage: $0 <version> <arch>"
VERSION="$1"
ARCH="$2"
case "$ARCH" in
  amd64|arm64) ;;
  *) die "unsupported arch '$ARCH' (want amd64 or arm64)" ;;
esac
[[ "$VERSION" =~ ^[A-Za-z0-9._+-]+$ ]] || die "invalid version '$VERSION'"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_DIR="${OUT_DIR:-$ROOT/dist}"
IMAGES_TXT="${IMAGES_TXT:-$ROOT/platformctl/internal/images/images.txt}"
ZSTD_LEVEL="${ZSTD_LEVEL:-10}"
BUNDLE="platform-bundle-${VERSION}-${ARCH}.tar.zst"

for tool in curl jq helm docker zstd tar sha256sum; do
  command -v "$tool" >/dev/null 2>&1 || die "required tool not found: $tool"
done
[[ -f "$IMAGES_TXT" ]] || die "image list not found: $IMAGES_TXT (generated by the image pre-pull work, issue #10; set IMAGES_TXT to override)"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
STAGE="$WORK/bundle"
mkdir -p "$STAGE/k3s" "$STAGE/images" "$STAGE/charts" "$OUT_DIR"

# --- pinned versions -------------------------------------------------------
if [[ -n "${CHARTS_JSON:-}" ]]; then
  cp "$CHARTS_JSON" "$WORK/charts.json"
elif [[ -n "${PLATFORMCTL:-}" ]]; then
  "$PLATFORMCTL" charts --json >"$WORK/charts.json"
else
  command -v go >/dev/null 2>&1 || die "go not found (or set PLATFORMCTL / CHARTS_JSON)"
  (cd "$ROOT/platformctl" && go run . charts --json) >"$WORK/charts.json"
fi
K3S_VERSION="$(jq -er '.k3s' "$WORK/charts.json")"
HELM_VERSION="$(jq -er '.helm' "$WORK/charts.json")"
CHART_MIRROR="$(jq -er '.chartMirror' "$WORK/charts.json")"
log "version=$VERSION arch=$ARCH k3s=$K3S_VERSION helm=$HELM_VERSION"

# --- k3s airgap images -----------------------------------------------------
K3S_TAG_ENC="${K3S_VERSION//+/%2B}"
K3S_FILE="k3s-airgap-images-${ARCH}.tar.zst"
K3S_URL="https://github.com/k3s-io/k3s/releases/download/${K3S_TAG_ENC}/${K3S_FILE}"
log "downloading $K3S_URL"
# Authenticated when GITHUB_TOKEN is set (CI): during GitHub Releases outages
# anonymous downloads have failed while authenticated ones kept working.
curl -fSL --retry 5 --retry-delay 5 ${GITHUB_TOKEN:+-H "Authorization: Bearer $GITHUB_TOKEN"} \
  -o "$STAGE/k3s/$K3S_FILE" "$K3S_URL"

# --- helm charts -----------------------------------------------------------
export HELM_CACHE_HOME="$WORK/helm/cache" HELM_CONFIG_HOME="$WORK/helm/config" HELM_DATA_HOME="$WORK/helm/data"
declare -A added_repos=()
# Fields are joined with the ASCII unit separator (\x1f), not tabs: bash merges
# consecutive tab delimiters, which dropped the empty repo fields of OCI charts.
while IFS=$'\x1f' read -r name repo repo_url chart version; do
  [[ -n "$name" ]] || continue
  [[ "$name" =~ ^[A-Za-z0-9._-]+$ && "$version" =~ ^[A-Za-z0-9._+-]+$ ]] || die "bad chart entry: $name $version"
  pull_dir="$WORK/pull/$name"
  mkdir -p "$pull_dir"
  mirror_ref="$CHART_MIRROR/${chart##*/}"
  if [[ -z "$repo_url" ]]; then
    log "helm pull $chart --version $version"
    helm pull "$chart" --version "$version" --destination "$pull_dir" \
      || { log "upstream failed; helm pull $mirror_ref"; helm pull "$mirror_ref" --version "$version" --destination "$pull_dir"; }
  else
    if [[ -z "${added_repos[$repo]:-}" ]]; then
      helm repo add "$repo" "$repo_url" --force-update >/dev/null || log "WARN: helm repo add $repo failed"
      added_repos[$repo]=1
    fi
    log "helm pull $repo/$chart --version $version"
    # Upstream unavailable (e.g. a GitHub Releases outage): use the GHCR mirror.
    helm pull "$repo/$chart" --version "$version" --destination "$pull_dir" \
      || { log "upstream failed; helm pull $mirror_ref"; helm pull "$mirror_ref" --version "$version" --destination "$pull_dir"; }
  fi
  shopt -s nullglob
  pulled=("$pull_dir"/*.tgz)
  shopt -u nullglob
  [[ ${#pulled[@]} -eq 1 ]] || die "expected one tarball for $name, got ${#pulled[@]}"
  mv "${pulled[0]}" "$STAGE/charts/${name}-${version}.tgz"
done < <(jq -r '.charts[] | [.name, (.repo // ""), (.repoUrl // ""), .chart, .version] | join("\u001f")' "$WORK/charts.json")

# --- platform images -------------------------------------------------------
mapfile -t IMAGES < <(sed -e 's/#.*$//' -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' "$IMAGES_TXT" | grep -v '^$' | sort -u)
[[ ${#IMAGES[@]} -gt 0 ]] || die "no images listed in $IMAGES_TXT"
for img in "${IMAGES[@]}"; do
  log "docker pull --platform linux/$ARCH $img"
  docker pull --quiet --platform "linux/$ARCH" "$img" >/dev/null
  got_arch="$(docker image inspect --format '{{.Architecture}}' "$img")"
  [[ "$got_arch" == "$ARCH" ]] || die "$img resolved to $got_arch, want $ARCH"
done
IMG_FILE="platform-images-${ARCH}.tar.zst"
log "docker save ${#IMAGES[@]} images -> $IMG_FILE"
docker save "${IMAGES[@]}" | zstd -q -f -T0 "-$ZSTD_LEVEL" -o "$STAGE/images/$IMG_FILE"

# --- manifest + checksums --------------------------------------------------
(cd "$STAGE" && find k3s images charts -type f | LC_ALL=C sort) >"$WORK/files.txt"
printf '%s\n' "${IMAGES[@]}" >"$WORK/images.txt"
jq -n \
  --arg version "$VERSION" --arg arch "$ARCH" \
  --arg k3s "$K3S_VERSION" --arg helm "$HELM_VERSION" \
  --arg created "$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
  --slurpfile charts "$WORK/charts.json" \
  --rawfile files "$WORK/files.txt" \
  --rawfile images "$WORK/images.txt" \
  '{version: $version, arch: $arch, k3s: $k3s, helm: $helm, created: $created,
    charts: [$charts[0].charts[] | {name, version}],
    images: ($images | split("\n") | map(select(length > 0))),
    files: ($files | split("\n") | map(select(length > 0)))}' >"$STAGE/manifest.json"
(cd "$STAGE" && xargs -d '\n' sha256sum <"$WORK/files.txt" >SHA256SUMS)

# --- package ---------------------------------------------------------------
# Contents are already compressed; a low level keeps packaging fast.
log "packaging $OUT_DIR/$BUNDLE"
tar -C "$STAGE" -cf - SHA256SUMS manifest.json k3s images charts | zstd -q -T0 -3 -o "$OUT_DIR/$BUNDLE" -f
(cd "$OUT_DIR" && sha256sum "$BUNDLE" >"$BUNDLE.sha256")
# GitHub release assets must be smaller than 2 GiB; the bundle is larger.
# Releases publish .part00, .part01, ... (the .sha256 covers the whole
# bundle); `platformctl` reassembles them, or: cat <bundle>.part* > <bundle>.
rm -f "$OUT_DIR/$BUNDLE".part*
(cd "$OUT_DIR" && split -b 1900M -d -a 2 "$BUNDLE" "$BUNDLE.part")
log "done: $OUT_DIR/$BUNDLE ($(du -h "$OUT_DIR/$BUNDLE" | cut -f1), $(ls "$OUT_DIR/$BUNDLE".part* | wc -l) part(s))"
